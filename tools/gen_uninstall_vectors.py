#!/usr/bin/env python3
"""Generate contract/uninstall-vectors.json from agent/uninstall.py.

The native agent must reproduce these codes, verifications and release tokens byte for byte.
Regenerate only when agent/uninstall.py changes on purpose: python tools/gen_uninstall_vectors.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "agent"))

from uninstall import code, derive_secret, normalize, release_token, verify

OUTPUT = ROOT / "contract" / "uninstall-vectors.json"
# Test-only key: never used outside these vectors.
MASTER = b"test-only-master-key-0123456789abcdef"
CLIENTS = ["client-1", "0123456789abcdef0123456789abcdef", "ação"]
COUNTERS = [1, 2, 20, 21, 1000, 2**40]


def build() -> dict[str, Any]:
    secrets = []
    for client in CLIENTS:
        secret = derive_secret(MASTER, client)
        secrets.append({"client_id": client, "secret": secret.hex(), "release": release_token(secret),
                        "codes": [{"counter": counter, "code": code(secret, counter)} for counter in COUNTERS]})
    first, second = derive_secret(MASTER, CLIENTS[0]), derive_secret(MASTER, CLIENTS[1])
    verify_cases = [
        (first, code(first, 1), 0), (first, code(first, 20), 0), (first, code(first, 21), 0),
        (first, code(first, 3), 3), (first, code(first, 4), 3), (first, code(first, 1).lower(), 0),
        (first, code(first, 2).replace("-", " "), 0), (second, code(first, 1), 0), (first, "00000-00000", 0),
        (first, "not a code", 0),
    ]
    return {
        "_comment": "Generated by tools/gen_uninstall_vectors.py from agent/uninstall.py; do not edit by hand.",
        "master_key": MASTER.decode("ascii"),
        "secrets": secrets,
        "verify": [{"secret": secret.hex(), "code": typed, "last_used": last, "result": verify(secret, typed, last)}
                   for secret, typed, last in verify_cases],
        "normalize": [{"input": text, "result": normalize(text)}
                      for text in ("abcde-fghjk", "ABCDE FGHJK", "O0IL1-ABCDE", "ABCDE-FGHJU", "ABCD", "")],
    }


def render() -> str:
    return json.dumps(build(), ensure_ascii=False, indent=2) + "\n"


def main() -> int:
    OUTPUT.write_text(render(), encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
